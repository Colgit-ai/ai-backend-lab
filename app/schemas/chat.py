from pydantic import BaseModel, Field, field_validator, ConfigDict
import logging
from datetime import datetime

logger = logging.getLogger(__name__)

class ChatRequest(BaseModel):
    message: str = Field(
        min_length=1, 
        max_length=1000, 
        description="The message to send to the LLM service"
    )

    @field_validator("message", mode="before")
    @classmethod
    def validate_message(cls, value: str):

        if not isinstance(value, str):
            logger.warning("Message must be a string")
            #Don't raise HTTPException inside Pydantic validators
            raise ValueError("Message must be a string") 

        value = value.strip()

        if not value:
            logger.error("Message cannot be empty or whitespace")
            raise ValueError("Message cannot be empty or whitespace")
            
        return value


class ChatResponse(BaseModel):
    message: str = Field(
        description="The original message sent to the LLM service"
    )
    response: str = Field(
        description="The response generated by the LLM service"
    )

class ConversationResponse(BaseModel):
    id:int
    user_message: str
    assistant_response: str
    created_at: datetime

    model_config = ConfigDict(from_attributes=True)